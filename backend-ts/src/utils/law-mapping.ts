const SORTED_MAPPINGS = Object.entries(RAW_LAW_MAPPING)
  .map(([key, value]) => ({
    key: normalizeArabicQuery(key),
    value,
    normalizedValue: normalizeArabicQuery(value),
  }))
  .sort((a, b) => b.key.length - a.key.length);

export type MappingResult = {
  matched: boolean;
  rewritten: string;
  matchedTerm: string | null;
  appendedLaw: string | null;
};

export const rewriteWithMapping = (normalizedQuery: string): MappingResult => {
  for (const { key, value, normalizedValue } of SORTED_MAPPINGS) {
    if (key.length === 0) continue;
    if (normalizedQuery.includes(key)) {
      if (normalizedQuery.includes(normalizedValue)) {
        return {
          matched: true,
          rewritten: normalizedQuery,
          matchedTerm: key,
          appendedLaw: null,
        };
      }
      return {
        matched: true,
        rewritten: `${normalizedQuery} ${value}`,
        matchedTerm: key,
        appendedLaw: value,
      };
    }
  }
  return {
    matched: false,
    rewritten: normalizedQuery,
    matchedTerm: null,
    appendedLaw: null,
  };
};
